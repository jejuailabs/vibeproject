import { test, expect } from "@playwright/test";

test("leaders edit vote contents from the list and board while existing selections and final results survive", async ({ page }, info) => {
  await page.route("**/*", (route) => {
    const url = new URL(route.request().url());
    return url.origin === "http://127.0.0.1:3108" && !url.pathname.startsWith("/api/") ? route.continue() : route.abort();
  });
  await page.goto("/?mobile=1");
  await page.getByLabel("미리보기 참가자").selectOption("jun");
  await page.locator(".pj-open").filter({ hasText: "첫걸음" }).click();
  await page.locator(".pj-step").filter({ hasText: "최종 아이디어·투표" }).click();
  await page.getByRole("button", { name: "새 투표 열기", exact: true }).click();
  const picker = page.getByRole("dialog", { name: "투표 후보 고르기", exact: true });
  await picker.getByRole("checkbox", { name: /문제 카드 2/ }).uncheck();
  await picker.getByRole("button", { name: "1장으로 투표 시작", exact: true }).click();
  const room = page.locator(".vote-card[data-vote-id]");
  await room.getByRole("button", { name: "투표하러 가기", exact: true }).click();
  await page.locator(".vote-tile").getByRole("button", { name: "투표", exact: true }).click();
  await page.getByRole("button", { name: "투표 목록", exact: true }).click();
  await room.getByRole("button", { name: "투표 수정", exact: true }).click();
  const editor = page.getByRole("dialog", { name: "투표 수정", exact: true });
  await expect(editor.getByRole("checkbox", { checked: true })).toHaveCount(1);
  await editor.getByLabel("수정할 투표 이름").fill("이번 주 함께 만들 프로젝트");
  await editor.getByRole("checkbox", { name: /문제 카드 2/ }).check();
  await editor.getByLabel("수정할 한 사람당 투표 수").selectOption("2");
  await editor.getByLabel("수정할 투표 시간").selectOption("720");
  await expect(editor.getByLabel("수정할 투표 시간").getByRole("option", { name: "72시간", exact: true })).toHaveCount(1);
  await editor.getByRole("button", { name: "수정 저장", exact: true }).click();
  await expect(editor).not.toBeVisible();
  await expect(room).toContainText("이번 주 함께 만들 프로젝트");
  await expect(room).toContainText("후보 문제 카드 2장 · 1/2명 참여 · 한 사람당 2표");
  await room.getByRole("button", { name: "투표하러 가기", exact: true }).click();
  await expect(page.locator(".pj-vote")).toContainText("내가 고른 카드 1/2");
  await page.getByRole("button", { name: "투표 목록", exact: true }).click();

  await page.getByLabel("미리보기 참가자").selectOption("seo");
  await expect(room.getByRole("button", { name: "투표 수정", exact: true })).toHaveCount(0);
  await room.getByRole("button", { name: "투표하러 가기", exact: true }).click();
  await expect(page.getByRole("button", { name: "투표 수정", exact: true })).toHaveCount(0);
  await page.locator(".vote-tile").filter({ hasText: "문제 카드 2" }).getByRole("button", { name: "투표", exact: true }).click();
  await page.getByRole("button", { name: "투표 목록", exact: true }).click();
  await page.getByLabel("미리보기 참가자").selectOption("jun");
  await room.getByRole("button", { name: "투표 수정", exact: true }).click();
  await editor.getByRole("checkbox", { name: /문제 카드 1/ }).uncheck();
  await expect(editor).toContainText("빼는 후보에 들어간 표는 취소됩니다");
  await editor.getByLabel("수정할 투표 시간").selectOption("0");
  await editor.getByRole("button", { name: "수정 저장", exact: true }).click();
  await expect(editor).not.toBeVisible();
  await expect(room).toContainText("후보 문제 카드 1장 · 1/2명 참여 · 한 사람당 1표");
  await room.getByRole("button", { name: "투표하러 가기", exact: true }).click();
  await expect(page.locator(".pj-vote")).toContainText("내가 고른 카드 0/1");
  // The editor is reachable from the vote screen too; unchanged deadline defaults to keep.
  await page.getByRole("button", { name: "투표 수정", exact: true }).click();
  await expect(editor.getByLabel("수정할 투표 시간")).toHaveValue("keep");
  await editor.getByLabel("수정할 투표 이름").fill("최종 프로젝트 고르기");
  expect(await editor.evaluate((el) => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await editor.getByRole("button", { name: "수정 저장", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "work/vote-edit-" + info.project.name + ".png" });
  await editor.getByRole("button", { name: "수정 저장", exact: true }).click();
  await page.locator(".vote-tile").getByRole("button", { name: "투표", exact: true }).click();
  await page.getByRole("button", { name: "투표 마감하기", exact: true }).click();
  await page.getByRole("button", { name: "투표 목록", exact: true }).click();
  await room.getByRole("button", { name: "투표 수정", exact: true }).click();
  await expect(editor.getByRole("checkbox")).toHaveCount(0);
  await expect(editor).toContainText("결과는 그대로 유지돼요");
  await editor.getByLabel("수정할 투표 이름").fill("마감된 프로젝트 투표");
  await editor.getByRole("button", { name: "수정 저장", exact: true }).click();
  await expect(room).toContainText("마감된 프로젝트 투표");
  await room.getByRole("button", { name: "대시보드", exact: true }).click();
  const dash = page.getByRole("dialog", { name: "투표 대시보드", exact: true });
  await expect(dash).toContainText("2/2명");
  await expect(dash).toContainText("2/2표");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
