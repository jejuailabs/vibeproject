import {test,expect} from '@playwright/test';
test('a thought grows through five questions, two drafts, readiness and history',async({page})=>{
 await page.goto('/preview');
 await page.getByLabel('무슨 일이었나요?').fill('첫 대화를 시작하기 어려워요');
 await page.getByLabel('언제, 누구에게, 무엇이 불편했나요?').fill('처음 간 모임에서 혼자 기다렸어요.');
 await page.getByRole('button',{name:'카드 올리기',exact:true}).click();
 const card=page.locator('.stage-thought .journey-note').filter({hasText:'첫 대화를 시작하기 어려워요'});
 await card.getByRole('button',{name:'이 생각 구체화하기'}).click();
 const editor=page.getByRole('dialog').getByRole('region',{name:'생각 구체화와 문제정의'});
 await editor.getByLabel('누가 겪나요?',{exact:true}).fill('모임에 처음 참석한 사람');
 await editor.getByRole('button',{name:'답변 임시 저장'}).click();
 await expect(editor.getByText('질문 답변을 저장했어요.',{exact:true})).toBeVisible();
 await page.getByRole('dialog').getByRole('button',{name:'닫기',exact:true}).click();
 await expect(card.getByText('구체화 중',{exact:true})).toBeVisible();
 await card.getByRole('button',{name:'이 생각 구체화하기'}).click();
 await expect(editor.getByLabel('누가 겪나요?',{exact:true})).toHaveValue('모임에 처음 참석한 사람');
 for(const [label,value] of [['언제, 어디서 일어나나요?','모임 시작 전'],['그 순간 무엇을 하려다 막히나요?','말 걸 상대를 찾지 못함'],['지금은 어떻게 해결하고 있나요?','카카오톡으로 진행자에게 물어봄'],['얼마나 자주 일어나나요?','처음 참석할 때마다']])await editor.getByLabel(label,{exact:true}).fill(value);
 await editor.getByLabel('무엇 때문에 바꿨나요?',{exact:true}).fill('참여 경험을 돌아봄');
 await editor.getByRole('button',{name:'저장하고 문제정의로'}).click();
 for(const [label,value] of [['왜 그게 문제인가요?','혼자 기다리다 참여를 포기함'],['해결되면 무엇이 달라지나요?','편하게 대화를 시작함'],['누가','처음 참석한 사람'],['어떤 상황에서','모임 시작 전'],['무엇 때문에','서로 관심사를 알기 어려움'],['어떤 어려움','말 걸 상대를 찾지 못하는 어려움'],['우리가 직접 바꿀 수 있는 부분','시작 전 소개 방식'],['협조가 필요하거나 바꾸기 어려운 부분','참가자의 참여 의사'],['이번 4주에서 다룰 범위','모임 시작 전 10분']])await editor.getByLabel(label,{exact:true}).fill(value);
 await editor.getByLabel('무엇 때문에 바꿨나요?',{exact:true}).fill('문제의 범위를 정함');
 await editor.getByRole('button',{name:'초안 저장',exact:true}).click();
 await expect(editor.getByRole('heading',{name:'문제정의카드 · 다음 저장은 초안 2'})).toBeVisible();
 await editor.getByLabel('이번 4주에서 다룰 범위',{exact:true}).fill('모임 시작 전 5분');
 await editor.getByLabel('무엇 때문에 바꿨나요?',{exact:true}).fill('동료 의견으로 더 작게 시작');
 await editor.getByLabel('문장에 앱 이름이나 만들 기능을 넣어').check();
 await editor.getByRole('button',{name:'선정 준비 완료',exact:true}).click();
 await expect(editor.getByText('선정 준비',{exact:true})).toBeVisible();
 await page.getByRole('dialog').getByText('이 생각의 전체 변화 이력',{exact:true}).click();
 const history=page.getByRole('dialog').locator('.wk-version');
 await expect(history).toContainText('모임 시작 전 10분');await expect(history).toContainText('모임 시작 전 5분');await expect(history).toContainText('동료 의견으로 더 작게 시작');
 await page.getByRole('dialog').getByRole('button',{name:'닫기',exact:true}).click();
 await expect(card.getByText('선정 준비 · 초안 2',{exact:true})).toBeVisible();
});
test('mobile owner can review solution wording and others read without edit access',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/preview');
 await page.getByRole('button',{name:/처음 온 사람도 편안한 커뮤니티/}).click();
 const editor=page.getByRole('dialog').getByRole('region',{name:'생각 구체화와 문제정의'});
 await editor.getByLabel('누가',{exact:true}).fill('AI 매칭 앱 사용자');
 await expect(editor.getByText(/해결 방법은 아직 열어두고/)).toBeVisible();
 await expect(editor.getByRole('button',{name:'선정 준비 완료',exact:true})).toBeDisabled();
 await editor.getByLabel('무엇 때문에 바꿨나요?',{exact:true}).fill('초안으로 검토');
 await editor.getByRole('button',{name:'초안 저장',exact:true}).click();
 expect(await page.getByRole('dialog').evaluate(e=>e.scrollWidth>e.clientWidth)).toBe(false);
 await page.screenshot({path:'work/refinement-mobile.png',fullPage:true});
 await page.getByRole('dialog').getByRole('button',{name:'닫기',exact:true}).click();
 await page.getByLabel('미리보기 참가자').selectOption('seo');
 await page.getByRole('button',{name:/처음 온 사람도 편안한 커뮤니티/}).click();
 await expect(page.getByRole('region',{name:'생각 구체화와 문제정의'})).toHaveCount(0);
 await page.getByRole('dialog').getByText('질문 답변·문제정의 초안 2',{exact:true}).click();
 await expect(page.getByRole('dialog').locator('.refinement-summary')).toContainText('AI 매칭 앱 사용자');
});
