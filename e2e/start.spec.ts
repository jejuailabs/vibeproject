import {test,expect} from '@playwright/test';
test('start screen leads from first thought directly through questions and problem definition',async({page})=>{
 await page.goto('/preview');
 const start=page.getByRole('region',{name:'프로젝트 시작 입력'});
 const steps=start.getByRole('navigation',{name:'시작 입력 단계'});
 await expect(steps.getByRole('button',{name:/처음 생각/})).toHaveAttribute('aria-current','step');
 await expect(start.getByText('누가 겪나요?',{exact:true})).toBeVisible();
 await expect(steps.getByRole('button',{name:/경험 구체화/})).toBeDisabled();
 await page.screenshot({path:'work/start-desktop.png',fullPage:false});
 await start.getByLabel('무슨 일이었나요?').fill('아침에 약속 준비를 놓쳐요');
 await start.getByLabel('언제, 누구에게, 무엇이 불편했나요?').fill('외출하기 직전 준비물을 찾느라 늦습니다.');
 await start.getByRole('button',{name:'카드 올리기',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(steps.getByRole('button',{name:/경험 구체화/})).toHaveAttribute('aria-current','step');
 const editor=start.getByRole('region',{name:'생각 구체화와 문제정의'});
 const answers=[['누가 겪나요?','출근하는 사람'],['언제, 어디서 일어나나요?','아침 집에서'],['그 순간 무엇을 하려다 막히나요?','준비물을 찾다가 출발이 늦어짐'],['지금은 어떻게 해결하고 있나요?','기억을 더듬으며 방을 다시 확인'],['얼마나 자주 일어나나요?','매주 두 번']];
 for(const [label,value] of answers)await editor.getByLabel(label,{exact:true}).fill(value);
 await page.screenshot({path:'work/start-questions.png',fullPage:false});
 await editor.getByRole('button',{name:'저장하고 문제정의로',exact:true}).click();
 await expect(steps.getByRole('button',{name:/문제정의 초안/})).toHaveAttribute('aria-current','step');
 for(const [label,value] of [['왜 그게 문제인가요?','출근 약속에 늦음'],['해결되면 무엇이 달라지나요?','여유 있게 출발'],['누가','출근하는 사람'],['어떤 상황에서','외출 직전'],['무엇 때문에','준비물 위치를 기억하기 어려움'],['어떤 어려움','준비물을 찾느라 출발이 지연되는 어려움'],['우리가 직접 바꿀 수 있는 부분','전날 준비 과정'],['협조가 필요하거나 바꾸기 어려운 부분','가족의 물건 이동'],['이번 4주에서 다룰 범위','아침 외출 준비']])await editor.getByLabel(label,{exact:true}).fill(value);
 await editor.getByLabel('무엇 때문에 바꿨나요?',{exact:true}).fill('실제 경험으로 문제를 정리');
 await editor.getByLabel('문장에 앱 이름이나 만들 기능을 넣어').check();
 await editor.getByRole('button',{name:'선정 준비 완료',exact:true}).click();
 await expect(editor.getByRole('status')).toContainText('선정 준비를 완료');
 const exhibition=page.getByRole('region',{name:'단계별 생각 전시'});
 await expect(exhibition.getByRole('region',{name:'경험 구체화 전시'})).toContainText('매주 두 번');
 await expect(exhibition.getByRole('region',{name:'문제정의 초안 전시'})).toContainText('전날 준비 과정');
 await expect(exhibition.getByRole('region',{name:'선정 준비 전시'})).toContainText('아침 외출 준비');
 const id=await start.getByLabel('작성 중인 생각 이어쓰기').inputValue();
 await start.getByRole('button',{name:'새 생각 시작',exact:true}).click();
 await expect(start.getByLabel('무슨 일이었나요?')).toHaveValue('');
 await start.getByLabel('작성 중인 생각 이어쓰기').selectOption(id);
 await expect(editor.getByLabel('이번 4주에서 다룰 범위',{exact:true})).toHaveValue('아침 외출 준비');
 await page.getByRole('navigation',{name:'프로젝트 진행 단계'}).getByRole('button',{name:/만들고 고치기/}).click();
 await page.locator('.page-heading').getByRole('button',{name:'생각 남기기',exact:true}).click();
 await expect(start.getByLabel('무슨 일이었나요?')).toBeVisible();
});

test('mobile participant starts and resumes questions above the shared board',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/preview');
 const start=page.getByRole('region',{name:'프로젝트 시작 입력'});
 await start.getByLabel('무슨 일이었나요?').fill('모바일 시작 기록');await start.getByLabel('언제, 누구에게, 무엇이 불편했나요?').fill('아침 준비가 어려워요');await start.getByLabel('아직은 나만 볼게요').check();
 await start.getByRole('button',{name:'카드 올리기',exact:true}).click();
 const editor=start.getByRole('region',{name:'생각 구체화와 문제정의'});
 await editor.getByLabel('누가 겪나요?',{exact:true}).fill('처음 준비하는 사람');
 await editor.getByRole('button',{name:'답변 임시 저장',exact:true}).click();
 const id=await start.getByLabel('작성 중인 생각 이어쓰기').inputValue();
 await start.getByRole('button',{name:'새 생각 시작',exact:true}).click();
 await start.getByLabel('작성 중인 생각 이어쓰기').selectOption(id);
 await expect(editor.getByLabel('누가 겪나요?',{exact:true})).toHaveValue('처음 준비하는 사람');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await start.scrollIntoViewIfNeeded();await page.screenshot({path:'work/start-mobile.png'});
 await page.getByLabel('미리보기 참가자').selectOption('seo');
 await expect(page.getByLabel('작성 중인 생각 이어쓰기').locator('option').filter({hasText:'모바일 시작 기록'})).toHaveCount(0);
});