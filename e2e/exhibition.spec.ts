import {test,expect} from '@playwright/test';
test('participants read each stage and feedback stays on draft 1 after draft 2 is saved',async({page})=>{
 test.setTimeout(60000);
 await page.goto('/preview');await page.getByLabel('미리보기 참가자').selectOption('seo');
 const board=page.getByRole('region',{name:'단계별 생각 전시'});
 const questions=board.getByRole('region',{name:'경험 구체화 전시'}).getByRole('article').filter({hasText:'처음 온 사람도 편안한 커뮤니티'});
 await expect(questions.locator('dt')).toHaveCount(5);
 await expect(questions).toContainText('진행자에게 소개를 부탁함');
 await questions.getByRole('button',{name:'피드백 0',exact:true}).click();
 await questions.getByLabel('이 내용에 피드백',{exact:true}).fill('처음 참석할 때 특히 어려웠던 순간은 언제인가요?');
 await questions.getByRole('button',{name:'피드백 남기기',exact:true}).click();
 await expect(questions).toContainText('처음 참석할 때 특히 어려웠던 순간은 언제인가요?');
 const first=board.getByRole('region',{name:'문제정의 초안 전시'}).getByRole('article').filter({hasText:'처음 온 사람도 편안한 커뮤니티'});
 await first.getByRole('button',{name:'피드백 0',exact:true}).click();
 await first.getByLabel('이 내용에 피드백',{exact:true}).fill('시작 전 5분에 집중하면 더 작게 실험할 수 있어요.');
 await first.getByRole('button',{name:'피드백 남기기',exact:true}).click();
 await page.getByLabel('미리보기 참가자').selectOption('min');
 await page.getByRole('button',{name:/처음 온 사람도 편안한 커뮤니티/}).click();
 const editor=page.getByRole('region',{name:'생각 구체화와 문제정의'});
 await editor.getByLabel('이번 4주에서 다룰 범위',{exact:true}).fill('시작 전 5분');
 await editor.getByLabel('무엇 때문에 바꿨나요?',{exact:true}).fill('서연의 피드백으로 범위를 좁힘');
 await editor.getByRole('button',{name:'초안 저장',exact:true}).click();
 await expect(editor.getByText('새 초안을 저장했어요.',{exact:false})).toBeVisible();
 await page.getByRole('dialog').getByRole('button',{name:'닫기',exact:true}).click();
 const lane=board.getByRole('region',{name:'문제정의 초안 전시'});
 const old=lane.getByRole('article').filter({hasText:'처음 온 사람도 편안한 커뮤니티'}).filter({has:page.locator('.exhibit-version b').getByText('초안 1',{exact:true})});
 const updated=lane.getByRole('article').filter({hasText:'처음 온 사람도 편안한 커뮤니티'}).filter({has:page.locator('.exhibit-version b').getByText('초안 2',{exact:true})});
 await old.getByRole('button',{name:'피드백 1',exact:true}).click();
 await expect(old).toContainText('시작 전 5분에 집중하면');
 await updated.getByRole('button',{name:'피드백 0',exact:true}).click();
 await expect(updated).not.toContainText('시작 전 5분에 집중하면');
 await expect(updated).toContainText('서연의 피드백으로 범위를 좁힘');
 await board.getByLabel('아이디어 흐름',{exact:true}).selectOption('i1');
 await expect(board.getByRole('heading',{name:'우리 동네의 남는 공간, 함께 쓸 수 없을까요?'})).toHaveCount(0);
 await board.getByRole('navigation',{name:'전시 단계'}).getByRole('button',{name:/문제정의 초안/}).click();
 await expect(board.getByRole('region',{name:'처음 생각 전시'})).toHaveCount(0);
 await page.screenshot({path:'work/exhibition-drafts.png',fullPage:true});
});
test('mobile stage filter allows inline feedback without page overflow and respects private cards',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/preview');
 await page.getByLabel('무슨 일이었나요?').fill('개인 전시 기록');await page.getByLabel('언제, 누구에게, 무엇이 불편했나요?').fill('비공개로 남길 경험');await page.getByLabel('아직은 나만 볼게요').check();await page.getByRole('button',{name:'카드 올리기',exact:true}).click();
 await expect(page.getByRole('button',{name:/개인 전시 기록/})).toBeVisible();
 await page.getByLabel('미리보기 참가자').selectOption('seo');
 const board=page.getByRole('region',{name:'단계별 생각 전시'});
 await expect(board.getByText('개인 전시 기록',{exact:true})).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await board.getByRole('navigation',{name:'전시 단계'}).getByRole('button',{name:/경험 구체화/}).click();
 const card=board.getByRole('article').first();await card.getByRole('button',{name:'피드백 0',exact:true}).click();await card.getByLabel('이 내용에 피드백',{exact:true}).fill('저도 처음 모임에서 같은 경험을 했어요.');await card.getByRole('button',{name:'피드백 남기기',exact:true}).click();
 await expect(card).toContainText('저도 처음 모임에서 같은 경험을 했어요.');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await card.scrollIntoViewIfNeeded();await page.screenshot({path:'work/exhibition-mobile.png'});
});
